const storageKey = "voxart-language";

type LanguageValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: CopyKey) => string;
};

const LanguageContext = createContext<LanguageValue | null>(null);

function storedLanguage(): Language {
  try {
    const saved = localStorage.getItem(storageKey);
    if (saved === "fil") return "ph";
    if (languages.some((item) => item.id === saved)) return saved as Language;
  } catch {
    /* private browsing can block storage */
  }
  return "en";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(storedLanguage);

  useEffect(() => {
    const speech = languages.find((item) => item.id === language)?.speech ?? "en";
    document.documentElement.lang = speech;
    try {
      localStorage.setItem(storageKey, language);
    } catch {
      /* ignore storage failures */
    }
  }, [language]);

  const value = useMemo<LanguageValue>(() => {
    const speech = languages.find((item) => item.id === language)?.speech ?? "en";
    return {
      language,
      setLanguage: setLanguageState,
      t: (key) => dictionary[speech][key],
    };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useLanguage must be used within LanguageProvider");
  return value;
}
